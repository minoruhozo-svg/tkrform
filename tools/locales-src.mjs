const outDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', 'locales');

export function register(rows) { add(...rows); }

export async function build() {
  // 拡張用の文言（locales-ext.mjs）があれば読み込む
  try {
    const ext = await import('./locales-ext.mjs');
    add(...ext.rows);
  } catch (e) {
    if (e.code !== 'ERR_MODULE_NOT_FOUND') throw e;
  }
  const seen = new Set();
  const ja = {}, en = {};
  for (const [k, j, e] of T) {
    if (seen.has(k)) throw new Error(`キーが重複しています: ${k}`);
    seen.add(k);
    ja[k] = j; en[k] = e;
  }
  fs.writeFileSync(path.join(outDir, 'ja.json'), JSON.stringify(ja, null, 2) + '\n');
  fs.writeFileSync(path.join(outDir, 'en.json'), JSON.stringify(en, null, 2) + '\n');
  console.log(`locales: ${seen.size} keys`);
}

await build();
