def badge_xy(box, where, r):
    x0, y0, x1, y1 = box
    g = r + 6
    if isinstance(where, tuple):
        return where
    return {
        "tl": (x0 - g + 4, y0 - g + 4), "tr": (x1 + g - 4, y0 - g + 4),
        "l": (x0 - g, (y0 + y1) / 2), "r": (x1 + g, (y0 + y1) / 2),
        "t": ((x0 + x1) / 2, y0 - g), "b": ((x0 + x1) / 2, y1 + g),
    }[where]


def edge_point(box, p):
    """丸の中心 p から枠へ向かうとき、枠の辺上でいちばん近い点。"""
    x0, y0, x1, y1 = box
    return (min(max(p[0], x0), x1), min(max(p[1], y0), y1))


def arrow(d, a, b, w):
    import math
    d.line([a, b], fill=RED, width=w)
    ang = math.atan2(b[1] - a[1], b[0] - a[0])
    L = w * 4.2
    p1 = (b[0] - L * math.cos(ang - 0.45), b[1] - L * math.sin(ang - 0.45))
    p2 = (b[0] - L * math.cos(ang + 0.45), b[1] - L * math.sin(ang + 0.45))
    d.polygon([b, p1, p2], fill=RED)


def load_boxes():
    """tools/e2e/manual-shots.mjs が出した boxes.json（画面の要素から取った枠の位置）があれば、上の A を置き換える。"""
    import json
    p = os.path.join(SRC, "boxes.json")
    if not os.path.exists(p):
        return
    with open(p, encoding="utf-8") as f:
        for name, v in json.load(f).items():
            A[name + ".png"] = [(tuple(box), num, where if isinstance(where, str) else tuple(where)) for box, num, where in v["boxes"]]


def main():
    load_boxes()
    os.makedirs(DST, exist_ok=True)
    for name, items in A.items():
        im = Image.open(os.path.join(SRC, name)).convert("RGB")
        W = im.size[0]
        k = max(W, 600) / 800          # 小さい画像（ポップアップ）でも、表示したときの太さがそろうように
        lw = max(2, round(3 * k))
        r = max(10, round(14 * k))
        font = ImageFont.truetype(FONT, max(12, round(17 * k)))
        d = ImageDraw.Draw(im)
        for box, num, where in items:
            d.rounded_rectangle(box, radius=max(3, round(5 * k)), outline=RED, width=lw)
        for box, num, where in items:
            cx, cy = badge_xy(box, where, r)
            cx = min(max(cx, r + 2), im.size[0] - r - 2)
            cy = min(max(cy, r + 2), im.size[1] - r - 2)
            if isinstance(where, tuple):
                ex, ey = edge_point(box, (cx, cy))
                dist = ((ex - cx) ** 2 + (ey - cy) ** 2) ** 0.5
                if dist > r + 6:
                    sx = cx + (ex - cx) * (r + 2) / dist
                    sy = cy + (ey - cy) * (r + 2) / dist
                    arrow(d, (sx, sy), (ex, ey), lw)
            d.ellipse([cx - r, cy - r, cx + r, cy + r], fill=RED, outline=WHITE, width=max(2, lw - 1))
            t = str(num)
            bb = d.textbbox((0, 0), t, font=font)
            d.text((cx - (bb[2] - bb[0]) / 2 - bb[0], cy - (bb[3] - bb[1]) / 2 - bb[1]), t, font=font, fill=WHITE)
        im.save(os.path.join(DST, name))
        print("ok", name)


if __name__ == "__main__":
    main()
